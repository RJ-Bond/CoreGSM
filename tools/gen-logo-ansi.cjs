// Renders docs/logo.png as true-colour terminal art (half-block characters) and
// writes the shell functions `logo_art_large` / `logo_art_small` between the
// "# LOGO-BEGIN" and "# LOGO-END" markers of tools/installer-head.sh and tools/coregsm.sh.
// Usage: node tools/gen-logo-ansi.cjs
const fs = require('fs');
const path = require('path');
const skia = require('../src/core-backend/node_modules/skia-canvas');

const ESC = '\\033';
const rst = `${ESC}[0m`;

async function render(img, cols) {
  // cols characters wide, cols/2 rows tall (each char holds two vertically stacked pixels)
  const w = cols, h = cols;
  const c = new skia.Canvas(w, h);
  const x = c.getContext('2d');
  x.imageSmoothingQuality = 'high';
  x.drawImage(img, 0, 0, w, h);
  const d = x.getImageData(0, 0, w, h).data;
  const px = (X, Y) => {
    const i = (Y * w + X) * 4;
    return d[i + 3] < 110 ? null : [d[i], d[i + 1], d[i + 2]];
  };
  const fg = (p) => `${ESC}[38;2;${p[0]};${p[1]};${p[2]}m`;
  const bg = (p) => `${ESC}[48;2;${p[0]};${p[1]};${p[2]}m`;
  const lines = [];
  for (let y = 0; y < h; y += 2) {
    let s = '';
    for (let X = 0; X < w; X++) {
      const t = px(X, y), b = px(X, y + 1);
      if (!t && !b) s += `${rst} `;
      else if (t && !b) s += `${rst}${fg(t)}▀`;
      else if (!t && b) s += `${rst}${fg(b)}▄`;
      else s += `${fg(t)}${bg(b)}▀`;
    }
    lines.push(s + rst);
  }
  return lines;
}

(async () => {
  const img = await skia.loadImage(path.join(__dirname, '..', 'docs', 'logo.png'));
  const large = await render(img, 26); // 26 columns x 13 rows
  const small = await render(img, 10); // 10 columns x 5 rows
  const fn = (name, lines) => `${name}() {\n  local i=0\n  local -a rows=(\n${lines.map((l) => `    '${l}'`).join('\n')}\n  )\n  printf '%s\\n' "\${rows[@]}" | while IFS= read -r l; do printf '%b\\n' "$l"; done\n}`;
  // "logo_art_rows NAME" prints the rows into the array `LOGO_ROWS` so that callers can put text next to them
  const body = `# LOGO-BEGIN (generated by tools/gen-logo-ansi.cjs from docs/logo.png; do not edit by hand)
logo_rows_large=(
${large.map((l) => `  '${l}'`).join('\n')}
)
logo_rows_small=(
${small.map((l) => `  '${l}'`).join('\n')}
)
# LOGO-END`;
  void fn;
  for (const f of ['installer-head.sh', 'coregsm.sh']) {
    const p = path.join(__dirname, f);
    let t = fs.readFileSync(p, 'utf8');
    const a = t.indexOf('# LOGO-BEGIN');
    const b = t.indexOf('# LOGO-END');
    if (a >= 0 && b > a) t = t.slice(0, a) + body + t.slice(b + '# LOGO-END'.length);
    else console.log('markers not found in', f);
    fs.writeFileSync(p, t);
  }
  console.log('large rows', large.length, 'small rows', small.length, 'bytes', body.length);
})();
